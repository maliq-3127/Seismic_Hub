// ----------------------------------------------------------------------
// 2. THE NODE (Mobile Phone) - Broadcasts Data
// ----------------------------------------------------------------------
class NodeScreen extends StatefulWidget {
  const NodeScreen({super.key});

  @override
  State<NodeScreen> createState() => _NodeScreenState();
}

class _NodeScreenState extends State<NodeScreen> {
  final DatabaseReference _database = FirebaseDatabase.instance.ref('sensor_network/node_1');
  bool _isStreaming = false;

  @override
  void initState() {
    super.initState();
    // Listen to the phone's gyroscope
    gyroscopeEventStream().listen((GyroscopeEvent event) {
      if (_isStreaming) {
        // Push the X, Y, Z data to Firebase RTDB instantly
        _database.set({
          'x': event.x,
          'y': event.y,
          'z': event.z,
          'timestamp': DateTime.now().millisecondsSinceEpoch,
        });
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Node Active')),
      body: Center(
        child: SwitchListTile(
          title: const Text('Stream Data to Hub'),
          value: _isStreaming,
          onChanged: (val) => setState(() => _isStreaming = val),
        ),
      ),
    );
  }
}

// ----------------------------------------------------------------------
// 3. THE HUB (Laptop) - Listens & Analyzes Danger
// ----------------------------------------------------------------------
class HubScreen extends StatefulWidget {
  const HubScreen({super.key});

  @override
  State<HubScreen> createState() => _HubScreenState();
}

class _HubScreenState extends State<HubScreen> {
  final DatabaseReference _database = FirebaseDatabase.instance.ref('sensor_network/node_1');
  
  double _x = 0, _y = 0, _z = 0;
  String _dangerLevel = "SAFE";
  Color _dangerColor = Colors.green;

  @override
  void initState() {
    super.initState();
    // Continuously listen to Firebase for changes
    _database.onValue.listen((DatabaseEvent event) {
      if (event.snapshot.value != null) {
        final data = event.snapshot.value as Map<dynamic, dynamic>;
        setState(() {
          _x = data['x'] ?? 0.0;
          _y = data['y'] ?? 0.0;
          _z = data['z'] ?? 0.0;
          _calculateDanger();
        });
      }
    });
  }

  // Direction 1 & 4: Data Processing / System Judgments
  void _calculateDanger() {
    // A simple judgment threshold. If rotation speed on any axis exceeds 3.0 rad/s
    if (_x.abs() > 3.0 || _y.abs() > 3.0 || _z.abs() > 3.0) {
      _dangerLevel = "CRITICAL: HIGH MOVEMENT";
      _dangerColor = Colors.red;
    } else if (_x.abs() > 1.5 || _y.abs() > 1.5) {
      _dangerLevel = "WARNING: UNSTABLE";
      _dangerColor = Colors.orange;
    } else {
      _dangerLevel = "SAFE";
      _dangerColor = Colors.green;
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Hub Dashboard')),
      body: Padding(
        padding: const EdgeInsets.all(24.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            // Exclusive Hub Menu: Danger Levels
            Container(
              padding: const EdgeInsets.all(20),
              decoration: BoxDecoration(
                color: _dangerColor.withOpacity(0.2),
                border: Border.all(color: _dangerColor, width: 2),
                borderRadius: BorderRadius.circular(12)
              ),
              child: Column(
                children: [
                  const Text("SYSTEM DANGER LEVEL", style: TextStyle(letterSpacing: 2)),
                  const SizedBox(height: 10),
                  Text(
                    _dangerLevel, 
                    style: TextStyle(fontSize: 28, fontWeight: FontWeight.bold, color: _dangerColor)
                  ),
                ],
              ),
            ),
            const SizedBox(height: 40),
            Text("X Axis: ${_x.toStringAsFixed(3)}"),
            Text("Y Axis: ${_y.toStringAsFixed(3)}"),
            Text("Z Axis: ${_z.toStringAsFixed(3)}"),
          ],
        ),
      ),
    );
  }
}